 --------------------------------------------------------------------------------
-- Пак "example" для мониторов вагонов (Media Display)
--------------------------------------------------------------------------------
-- Файлы пака в materials/ms_screen_packs/example:
--   advert_1..advert_3   — статичные рекламы (DXT1);
--   anim_demo            — ОДНА анимированная текстура: .vtf с 8 кадрами,
--                          в .vmt прокси AnimatedTexture (кадры крутит сам
--                          движок — нагрузки на сервер и клиент нет).
-- Регистрация сообщает меню Утилит человеческое имя и описание пака; fps
-- анимации по умолчанию читается из .vmt, здесь можно переопределить её и
-- задать паузу после показа (hold).
--
-- ads — запасной список реклам (план Б для Workshop): обычно система сама
-- находит файлы пака сканом, но если на какой-то сборке file-функции не видят
-- содержимое чужих GMA, список выручит. Строки = статичные картинки,
-- таблицы = анимированные (frames = число кадров в .vtf).
--------------------------------------------------------------------------------

local DESC = "Демонстрационные рекламы, встроенные в аддон ms_screen_pack_example."

local ANIMS = {
	-- Настройки анимаций: имя текстуры/папки внутри пака -> параметры.
	-- anim_demo: 8 кадров по 8 fps (fps можно НЕ указывать — возьмётся
	-- из .vmt), после проигрывания пауза 1 секунда, затем смена рекламы.
	["anim_demo"] = { hold = 1 },
}

-- План Б для Workshop: перечень реклам пака явным списком.
local ADS = {
	"advert_1", "advert_2", "advert_3",
	{ base = "anim_demo", anim = true, frames = 8 },
}

local function register()
	if MSD_Packs then
		MSD_Packs.RegisterPack("example", "Пример пака", DESC, ANIMS, ADS)
	else
		-- Библиотека мониторов ещё не загрузилась — сохраняем заявку,
		-- она будет применена автоматически после загрузки sh_tvscreens_packs.lua
		MSD_Packs_Pending = MSD_Packs_Pending or {}
		table.insert(MSD_Packs_Pending, {
			id = "example",
			name = "Пример пака",
			desc = DESC,
			opts = ANIMS,
			ads = ADS,
		})
	end
end

register()
